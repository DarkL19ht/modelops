
"""HTTP inference for the currently promoted, local ModelOps champion."""

import hashlib
import hmac
import io
import logging
import os
from datetime import datetime, timezone
from pathlib import Path
from threading import RLock
from typing import Literal

import joblib
import numpy as np
import pandas as pd
from fastapi import FastAPI, Header, HTTPException
from pydantic import BaseModel, ConfigDict, Field, model_validator

from src.modelops.train import FEATURES, ROOT


logger = logging.getLogger(__name__)


class CustomerInput(BaseModel):
    """Validated customer features accepted by the API."""

    model_config = ConfigDict(extra="forbid")

    customer_id: str | None = Field(
        default=None,
        min_length=1,
        max_length=64,
    )

    tenure_months: int = Field(
        ge=0,
        le=120,
    )

    monthly_spend: float = Field(
        ge=0,
        le=10_000,
        allow_inf_nan=False,
    )

    support_tickets_90d: int = Field(
        ge=0,
        le=100,
    )

    logins_30d: int = Field(
        ge=0,
        le=10_000,
    )

    monthly_contract: Literal[0, 1]


class BatchInput(BaseModel):
    """A bounded list of customers for batch inference."""

    customers: list[CustomerInput] = Field(
        min_length=1,
        max_length=100,
    )

    @model_validator(mode="after")
    def distinct_customer_ids(self):
        ids = [
            customer.customer_id
            for customer in self.customers
            if customer.customer_id is not None
        ]

        if len(ids) != len(set(ids)):
            raise ValueError(
                "customer_id values must be unique within a batch"
            )

        return self


class ChampionStore:
    """
    Hold a validated champion model in memory.

    Reload swaps the in-memory model only after the
    replacement artifact has loaded successfully.
    """

    def __init__(self, model_path: Path):
        self.path = Path(model_path)
        self.lock = RLock()
        self.model = None
        self.sha256 = None
        self.loaded_at_utc = None

    def reload(self) -> dict:
        # Load only trusted files generated by this project.
        # joblib uses pickle and is unsafe for untrusted files.
        payload = self.path.read_bytes()

        candidate = joblib.load(
            io.BytesIO(payload)
        )

        if (
            not callable(getattr(candidate, "predict", None))
            or not callable(
                getattr(candidate, "predict_proba", None)
            )
        ):
            raise ValueError(
                "Champion does not implement classifier inference"
            )

        column_names = getattr(
            candidate,
            "feature_names_in_",
            None,
        )

        if (
            column_names is None
            or list(column_names) != FEATURES
        ):
            raise ValueError(
                "Champion model has incompatible feature names"
            )

        classes = list(
            getattr(candidate, "classes_", [])
        )

        if classes != [0, 1]:
            raise ValueError(
                "Champion model must classify labels [0, 1]"
            )

        digest = hashlib.sha256(
            payload
        ).hexdigest()

        loaded_at = datetime.now(
            timezone.utc
        ).isoformat(timespec="seconds")

        # Existing predictions can finish with their
        # previous model reference. New requests get
        # the replacement model.
        with self.lock:
            previous_sha = self.sha256

            self.model = candidate
            self.sha256 = digest
            self.loaded_at_utc = loaded_at

        return {
            "previous_sha256": previous_sha,
            "model_sha256": digest,
        }

    def snapshot(self):
        with self.lock:
            if self.model is None:
                self.reload()

            return (
                self.model,
                self.sha256,
                self.loaded_at_utc,
            )


def _get_snapshot(store: ChampionStore):
    try:
        return store.snapshot()

    except Exception:
        logger.exception(
            "Failed to load the active champion model"
        )

        raise HTTPException(
            status_code=503,
            detail="Active model unavailable",
        ) from None


def _predict(
    store: ChampionStore,
    customers: list[CustomerInput],
) -> dict:
    model, sha256, _ = _get_snapshot(store)

    frame = pd.DataFrame(
        [
            {
                name: getattr(customer, name)
                for name in FEATURES
            }
            for customer in customers
        ],
        columns=FEATURES,
    )

    try:
        predictions = np.asarray(
            model.predict(frame)
        )

        probabilities = np.asarray(
            model.predict_proba(frame),
            dtype=float,
        )[:, 1]

        if (
            len(predictions) != len(customers)
            or len(probabilities) != len(customers)
            or not np.isfinite(probabilities).all()
            or (
                (probabilities < 0)
                | (probabilities > 1)
            ).any()
            or not np.isin(
                predictions,
                [0, 1],
            ).all()
        ):
            raise ValueError(
                "Invalid model output"
            )

    except Exception:
        logger.exception(
            "Active champion inference failed"
        )

        raise HTTPException(
            status_code=503,
            detail="Model inference unavailable",
        ) from None

    return {
        "model_sha256": sha256,
        "predictions": [
            {
                "customer_id": customer.customer_id,
                "predicted_churn": int(label),
                "churn_probability": round(
                    float(probability),
                    6,
                ),
            }
            for customer, label, probability in zip(
                customers,
                predictions,
                probabilities,
                strict=True,
            )
        ],
    }


def create_app(
    model_path: Path | None = None,
    admin_token: str | None = None,
) -> FastAPI:
    app = FastAPI(
        title="ModelOps Inference API",
        version="0.1.0",
    )

    store = ChampionStore(
        model_path
        or ROOT / "artifacts/churn_model.joblib"
    )

    token = (
        os.getenv("MODELOPS_ADMIN_TOKEN", "")
        if admin_token is None
        else admin_token
    )

    @app.get("/health")
    def health():
        _, sha256, _ = _get_snapshot(store)

        return {
            "status": "ok",
            "service": "ModelOps inference API",
            "model_sha256": sha256,
        }

    @app.get("/model")
    def model_info():
        model, sha256, loaded_at = _get_snapshot(store)

        return {
            "model_sha256": sha256,
            "loaded_at_utc": loaded_at,
            "model_type": type(model).__name__,
            "features": FEATURES,
        }

    @app.post("/predict")
    def predict(customer: CustomerInput):
        result = _predict(
            store,
            [customer],
        )

        return {
            "model_sha256": result["model_sha256"],
            **result["predictions"][0],
        }

    @app.post("/predict/batch")
    def batch_predict(batch: BatchInput):
        return _predict(
            store,
            batch.customers,
        )

    @app.post("/admin/reload")
    def reload_model(
        x_admin_token: str | None = Header(
            default=None
        ),
    ):
        if not token:
            raise HTTPException(
                status_code=503,
                detail="Model reload is disabled",
            )

        if (
            x_admin_token is None
            or not hmac.compare_digest(
                x_admin_token,
                token,
            )
        ):
            raise HTTPException(
                status_code=403,
                detail="Invalid admin token",
            )

        try:
            return {
                "status": "reloaded",
                **store.reload(),
            }

        except Exception:
            logger.exception(
                "Champion reload failed; "
                "previous in-memory model retained"
            )

            raise HTTPException(
                status_code=503,
                detail="Champion reload failed",
            ) from None

    return app


app = create_app()
